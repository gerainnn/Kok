# Система уникальных вопросов без повторений
# ============================================================
# Хранит множества индексов уже заданных вопросов для каждого chat_id
_asked: dict[int, set[int]] = defaultdict(set)
# Индексы по категориям для быстрого доступа
_cat_indices: dict[str, list[int]] = defaultdict(list)

def _build_indices():
    """Строим индексы категорий при первом вызове."""
    if _cat_indices:
        return
    for i, q in enumerate(QUESTIONS):
        _cat_indices[q["cat"]].append(i)
        _cat_indices["any"].append(i)

_build_indices()


def random_question(category: str = "any", chat_id: int = 0) -> dict:
    """
    Возвращает вопрос, которого ещё не было для данного chat_id.
    Если все вопросы исчерпаны — сбрасывает историю и начинает заново.
    """
    _build_indices()
    
    cat = category if category in _cat_indices else "any"
    pool = _cat_indices[cat]
    asked = _asked[chat_id]
    
    # Фильтруем доступные (ещё не задававшиеся)
    available = [i for i in pool if i not in asked]
    
    # Если закончились — сбрасываем для этой категории
    if not available:
        # Убираем из asked только индексы этой категории
        for idx in pool:
            asked.discard(idx)
        available = pool[:]
    
    # Выбираем случайный
    idx = random.choice(available)
    asked.add(idx)
    
    return QUESTIONS[idx]


def reset_asked(chat_id: int) -> None:
    """Сбросить историю вопросов для пользователя."""
    _asked.pop(chat_id, None)


def get_stats() -> dict:
    """Возвращает статистику по базе вопросов."""
    return {
        "total": len(QUESTIONS),
        "categories": {k: len(v) for k, v in _cat_indices.items() if k != "any"},
    }
