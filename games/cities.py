SKIP_LETTERS = set("ьъыё")


def first_alpha(word: str) -> str:
    return word[0].lower() if word else ""


def last_letter(word: str) -> str:
    """Возвращает последнюю букву слова, пропуская ь/ъ/ы."""
    word = word.lower().strip()
    for ch in reversed(word):
        if ch.isalpha() and ch not in SKIP_LETTERS:
            return ch
    return ""


def next_letter_for_bot(player_word: str) -> str:
    return last_letter(player_word)


def bot_pick_city(letter: str, used: set[str]) -> str | None:
    pool = CITIES_BY_LETTER.get(letter, [])
    candidates = [c for c in pool if c not in used]
    if not candidates:
        return None
    return random.choice(candidates)


def is_known_city(name: str) -> bool:
    name = name.lower().strip()
    letter = first_alpha(name)
    return name in CITIES_BY_LETTER.get(letter, [])
