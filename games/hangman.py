"""Виселица: список слов и стадии."""
import random

WORDS = [
    "питон", "телеграм", "клавиатура", "космос", "программа",
    "разработчик", "функция", "переменная", "интернет", "компьютер",
    "алгоритм", "пингвин", "шоколад", "путешествие", "велосипед",
    "библиотека", "будильник", "мороженое", "приключение", "вселенная",
]

STAGES = [
    "  +---+\n      |\n      |\n      |\n     ===",
    "  +---+\n  O   |\n      |\n      |\n     ===",
    "  +---+\n  O   |\n  |   |\n      |\n     ===",
    "  +---+\n  O   |\n /|   |\n      |\n     ===",
    "  +---+\n  O   |\n /|\\  |\n      |\n     ===",
    "  +---+\n  O   |\n /|\\  |\n /    |\n     ===",
    "  +---+\n  O   |\n /|\\  |\n / \\  |\n     ===",
]

MAX_MISTAKES = len(STAGES) - 1


def random_word() -> str:
    return random.choice(WORDS)


def render_word(word: str, opened: set[str]) -> str:
    return " ".join(ch.upper() if ch in opened else "_" for ch in word)
